// ===== HELPER FUNCTIONS =====
window.SwedishPerfumeCatalog.getShopifyProductByPerfumeId = function(perfumeId) {
  for (let brandKey in this) {
    if (Array.isArray(this[brandKey])) {
      const perfume = this[brandKey].find(p => p.id === perfumeId);
      if (perfume && perfume.shopifyProduct) {
        return perfume.shopifyProduct;
      }
    }
  }
  return null;
};

window.SwedishPerfumeCatalog.getShopifyProductByNumber = function(number) {
  const numStr = number.toString().padStart(3, '0');
  
  for (let brandKey in this) {
    if (Array.isArray(this[brandKey])) {
      const perfume = this[brandKey].find(p => 
        p.productNumbers && p.productNumbers.includes(numStr)
      );
      if (perfume && perfume.shopifyProduct) {
        return perfume.shopifyProduct;
      }
    }
  }
  return null;
};

window.SwedishPerfumeCatalog.search = function(query) {
  if (!query || query.length < 2) return [];
  
  const results = [];
  const queryLower = query.toLowerCase().trim();
  
  for (let brandKey in this) {
    if (Array.isArray(this[brandKey])) {
      this[brandKey].forEach(perfume => {
        const searchableText = [
          perfume.name,
          perfume.brand,
          perfume.inspiredBy,
          perfume.year,
          ...(perfume.top_notes || []),
          ...(perfume.heart_notes || []),
          ...(perfume.base_notes || []),
          ...(perfume.productNumbers || [])
        ].join(' ').toLowerCase();
        
        if (searchableText.includes(queryLower)) {
          results.push(perfume);
        }
      });
    }
  }
  
  return results.sort((a, b) => a.name.localeCompare(b.name));
};

window.SwedishPerfumeCatalog.findById = function(id) {
  for (let brandKey in this) {
    if (Array.isArray(this[brandKey])) {
      const found = this[brandKey].find(p => p.id === id);
      if (found) return found;
    }
  }
  return null;
};

